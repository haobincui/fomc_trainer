class SentimentClosenessReportError(RuntimeError):
    """The estimator-to-report contract or create-only publication failed."""


def _utc_now() -> str:
    return (
        datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    )


def _canonical(value: Any) -> str:
    try:
        return json.dumps(
            value,
            allow_nan=False,
            ensure_ascii=False,
            separators=(",", ":"),
            sort_keys=True,
        )
    except (TypeError, ValueError) as exc:
        raise SentimentClosenessReportError(
            f"non-canonical JSON payload: {exc}"
        ) from exc


def _sha256_file(path: Path) -> str:
    return _delivery._sha256_file(path)


def _binding(path: Path, *, payload_sha256: str | None = None) -> dict[str, Any]:
    try:
        return _delivery._binding(path, payload_sha256=payload_sha256)
    except _delivery.BetaTechnicalReportError as exc:
        raise SentimentClosenessReportError(str(exc)) from exc


def _intended_binding(staged_path: Path, final_path: Path) -> dict[str, Any]:
    value = _binding(staged_path)
    value["path"] = str(final_path.expanduser().resolve())
    return value


def _repo_relative(path: Path) -> str:
    resolved = path.expanduser().resolve()
    try:
        return resolved.relative_to(ROOT).as_posix()
    except ValueError as exc:
        raise SentimentClosenessReportError(
            f"portable report source is outside repository root: {resolved}"
        ) from exc


def _finite(name: str, value: Any) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise SentimentClosenessReportError(f"{name} must be numeric")
    number = float(value)
    if not math.isfinite(number):
        raise SentimentClosenessReportError(f"{name} must be finite")
    return number


def _integer(name: str, value: Any, *, positive: bool = False) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise SentimentClosenessReportError(f"{name} must be an integer")
    if value < (1 if positive else 0):
        adjective = "positive" if positive else "non-negative"
        raise SentimentClosenessReportError(f"{name} must be {adjective}")
    return value


def _metric_id(value: Any) -> str:
    if not isinstance(value, str) or value not in METRIC_ALIASES:
        raise SentimentClosenessReportError(f"unknown closeness metric: {value!r}")
    return METRIC_ALIASES[value]


