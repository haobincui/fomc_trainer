def _number_text(value: float) -> str:
    return f"{float(value):+.6f}"


def _ci_text(row: Mapping[str, Any]) -> str:
    return f"[{float(row['ci_lower']):+.6f}, {float(row['ci_upper']):+.6f}]"


def _zero_relation(row: Mapping[str, Any]) -> str:
    low = float(row["ci_lower"])
    high = float(row["ci_upper"])
    if low > 0.0:
        return "entirely above zero"
    if high < 0.0:
        return "entirely below zero"
    return "includes zero"


def _source(
    *, source_id: str, label: str, binding: Mapping[str, Any], executed_at: str
) -> dict[str, Any]:
    path = _repo_relative(Path(str(binding["path"])))
    escaped = path.replace("'", "''")
    return {
        "id": source_id,
        "label": label,
        "path": path,
        "query": {
            "engine": "duckdb",
            "language": "sql",
            "sql": f"SELECT * FROM read_json_auto('{escaped}')",
            "description": (
                "Reads the sealed estimator input or result artifact. Report "
                "datasets are deterministic, bounded projections validated by the "
                "authoritative closeness loader."
            ),
            "executed_at": executed_at,
            "tables_used": [path],
        },
    }


