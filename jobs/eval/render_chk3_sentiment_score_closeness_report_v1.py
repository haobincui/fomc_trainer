def _extract_source_bindings(
    *, report_model: Mapping[str, Any], loaded: Mapping[str, Any]
) -> dict[str, Any]:
    explicit = report_model.get("source_bindings")
    if isinstance(explicit, Mapping):
        result = copy.deepcopy(dict(explicit))
        # The estimator report model calls this same binding ``manifest``.
        # The report contract uses one unambiguous provenance key and must not
        # expose the same file twice under two source IDs.
        result.pop("manifest", None)
    else:
        manifest = loaded.get("manifest")
        if not isinstance(manifest, Mapping):
            raise SentimentClosenessReportError("estimator manifest is missing")
        artifacts = manifest.get("artifacts")
        inputs = manifest.get("inputs")
        if not isinstance(artifacts, Mapping):
            raise SentimentClosenessReportError("estimator artifact bindings missing")
        result = {
            name: copy.deepcopy(artifacts[name])
            for name in (
                "meeting_aggregates",
                "estimates",
                "contrasts",
                "diagnostics",
            )
        }
        if isinstance(inputs, Mapping):
            for name, value in inputs.items():
                if isinstance(value, Mapping):
                    result[str(name)] = copy.deepcopy(dict(value))
    source_manifest = report_model.get("source_manifest_binding")
    if not isinstance(source_manifest, Mapping):
        source_manifest = loaded.get("manifest_binding")
    result["estimator_manifest"] = copy.deepcopy(dict(source_manifest))
    return result


