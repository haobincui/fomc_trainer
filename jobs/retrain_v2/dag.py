def build_plan(
    dag: Mapping[str, Any],
    *,
    repo_root: str | Path,
    run_id: str,
    dataset_release_id: str | None = None,
    base_release_id: str | None = None,
    reward_registry_path: str | Path = "src/open_r1/trainer/rewards/reward_register.py",
) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    base_id = _coalesce_base_release_id(
        base_release_id=base_release_id,
        dataset_release_id=dataset_release_id,
    )
    static = validate_dag(dag, repo_root=root, check_rewards=False)
    registry = _resolve_repo_path(
        root, str(reward_registry_path), label="reward registry"
    )
    missing_rewards = sorted(_required_rewards(dag) - registered_reward_names(registry))
    run_root = _resolve_repo_path(
        root, f"{dag['paths']['output_root']}/{run_id}", label="run root"
    )
    stages: dict[str, Any] = {}
    for stage_id in STAGE_IDS:
        stage = resolve_template(
            dag["stages"][stage_id],
            run_id=run_id,
            base_release_id=base_id,
        )
        record: dict[str, Any] = {
            "kind": stage["kind"],
            "parent": stage["parent"],
            "artifact": stage["artifact"],
            "launcher": stage["launcher"],
        }
        if stage_id in UPSTREAM_STAGE_IDS:
            config_path = run_root / "resolved_configs" / f"{stage_id}.yaml"
            record.update(
                {
                    "status": "pending",
                    "dataset": stage["dataset"],
                    "config": str(config_path.relative_to(root)),
                    "training": _command_for_stage(stage_id, config_path),
                }
            )
        elif stage_id in DOWNSTREAM_STAGE_IDS:
            record.update(
                {
                    "status": "awaiting_derived_data",
                    "dataset_template": stage["dataset"],
                    "config_template": stage["config"],
                    "training": None,
                }
            )
        stages[stage_id] = record
    return {
        "status": "blocked" if missing_rewards else "upstream_ready",
        "run_id": _validate_identifier(run_id, label="run_id"),
        "base_release_id": base_id,
        "dataset_release_id": base_id,
        "dag": static,
        "missing_rewards": missing_rewards,
        "run_manifest": str((run_root / "run_manifest.json").relative_to(root)),
        "stages": stages,
    }


