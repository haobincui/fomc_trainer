class DagValidationError(ValueError):
    """Raised when a DAG, release, or run violates an immutable invariant."""


def _utc_now() -> str:
    return (
        datetime.now(timezone.utc)
        .replace(microsecond=0)
        .isoformat()
        .replace("+00:00", "Z")
    )


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise DagValidationError(message)


def _load_mapping(path: Path, *, label: str) -> dict[str, Any]:
    if not path.is_file():
        raise DagValidationError(f"{label} does not exist: {path}")
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise DagValidationError(f"Unable to parse {label}: {path}") from exc
    if not isinstance(payload, dict):
        raise DagValidationError(f"{label} must contain a mapping: {path}")
    return payload


def _load_json_mapping(path: Path, *, label: str) -> dict[str, Any]:
    if not path.is_file():
        raise DagValidationError(f"{label} does not exist: {path}")
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise DagValidationError(f"Unable to parse {label}: {path}") from exc
    if not isinstance(payload, dict):
        raise DagValidationError(f"{label} must contain an object: {path}")
    return payload


def load_dag(path: str | Path = DEFAULT_DAG) -> dict[str, Any]:
    return _load_mapping(Path(path), label="DAG config")


def _validate_identifier(value: str, *, label: str) -> str:
    if not IDENTIFIER_RE.fullmatch(value):
        raise DagValidationError(
            f"{label} must match {IDENTIFIER_RE.pattern!r}; received {value!r}"
        )
    return value


def _coalesce_base_release_id(
    *,
    base_release_id: str | None,
    dataset_release_id: str | None,
) -> str:
    if base_release_id and dataset_release_id and base_release_id != dataset_release_id:
        raise DagValidationError(
            "--base-release-id and legacy --dataset-release-id disagree"
        )
    value = base_release_id or dataset_release_id
    if not value:
        raise DagValidationError(
            "A base release is required via --base-release-id or --dataset-release-id"
        )
    return _validate_identifier(value, label="base_release_id")


def _resolve_repo_path(repo_root: Path, value: str, *, label: str) -> Path:
    candidate = Path(value)
    _require(
        not candidate.is_absolute(), f"{label} must be repository-relative: {value}"
    )
    root = repo_root.resolve()
    resolved = (root / candidate).resolve()
    try:
        resolved.relative_to(root)
    except ValueError as exc:
        raise DagValidationError(f"{label} escapes the repository: {value}") from exc
    return resolved


def _resolve_within(root: Path, value: str, *, label: str) -> Path:
    candidate = Path(value)
    _require(not candidate.is_absolute(), f"{label} must be relative: {value}")
    resolved_root = root.resolve()
    resolved = (resolved_root / candidate).resolve()
    try:
        resolved.relative_to(resolved_root)
    except ValueError as exc:
        raise DagValidationError(f"{label} escapes its release: {value}") from exc
    return resolved


def _replace_tokens(
    value: Any,
    *,
    run_id: str,
    base_release_id: str,
    derived_release_id: str | None,
) -> Any:
    if isinstance(value, str):
        rendered = (
            value.replace(TOKEN_RUN_ID, run_id)
            .replace(TOKEN_BASE_RELEASE_ID, base_release_id)
            .replace(TOKEN_DATASET_RELEASE_ID, base_release_id)
        )
        if derived_release_id is not None:
            rendered = rendered.replace(TOKEN_DERIVED_RELEASE_ID, derived_release_id)
        return rendered
    if isinstance(value, list):
        return [
            _replace_tokens(
                item,
                run_id=run_id,
                base_release_id=base_release_id,
                derived_release_id=derived_release_id,
            )
            for item in value
        ]
    if isinstance(value, dict):
        return {
            key: _replace_tokens(
                item,
                run_id=run_id,
                base_release_id=base_release_id,
                derived_release_id=derived_release_id,
            )
            for key, item in value.items()
        }
    return value


def resolve_template(
    value: Any,
    *,
    run_id: str,
    dataset_release_id: str | None = None,
    base_release_id: str | None = None,
    derived_release_id: str | None = None,
) -> Any:
    _validate_identifier(run_id, label="run_id")
    base_id = _coalesce_base_release_id(
        base_release_id=base_release_id,
        dataset_release_id=dataset_release_id,
    )
    if derived_release_id is not None:
        _validate_identifier(derived_release_id, label="derived_release_id")
    return _replace_tokens(
        copy.deepcopy(value),
        run_id=run_id,
        base_release_id=base_id,
        derived_release_id=derived_release_id,
    )


def registered_reward_names(registry_path: str | Path) -> set[str]:
    """Read literal keys without importing trainer code or starting a judge."""

    path = Path(registry_path)
    if not path.is_file():
        raise DagValidationError(f"Reward registry does not exist: {path}")
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Assign, ast.AnnAssign)):
            continue
        targets: Iterable[ast.expr]
        if isinstance(node, ast.Assign):
            targets = node.targets
            value = node.value
        else:
            targets = (node.target,)
            value = node.value
        if not any(
            isinstance(target, ast.Name) and target.id == "REWARD_FUNCS_REGISTRY"
            for target in targets
        ):
            continue
        if isinstance(value, ast.Dict):
            for key in value.keys:
                if isinstance(key, ast.Constant) and isinstance(key.value, str):
                    names.add(key.value)
    return names


def _required_rewards(dag: Mapping[str, Any]) -> set[str]:
    required: set[str] = set()
    for stage in dag.get("stages", {}).values():
        if isinstance(stage, dict):
            required.update(stage.get("required_rewards", []) or [])
    return required


def _chk2_reward_contract(stage: Mapping[str, Any]) -> tuple[str, Mapping[str, int]]:
    required = stage.get("required_rewards")
    _require(
        isinstance(required, list) and len(required) == 1,
        "chk2 must require exactly one grounded-analysis reward",
    )
    reward_name = str(required[0])
    _require(
        reward_name in CHK2_REWARD_CONTRACTS,
        f"Unsupported chk2 reward contract: {reward_name}",
    )
    return reward_name, CHK2_REWARD_CONTRACTS[reward_name]


