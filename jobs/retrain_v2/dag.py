"""Fail-closed orchestration for the immutable retrain_v2 checkpoint DAG.

The checkpoint graph is ``chk0 -> chk1 -> chk2 -> {chk3, chk4}``, while data is
bound in two phases.  ``init-run`` pins only the base analysis release needed by
chk1/chk2.  After chk2 is sealed, ``bind-derived-data`` atomically binds an
independent release whose inputs were generated by that exact chk2 artifact.
This module validates, binds, and seals artifacts; it never trains a model or
builds a dataset.
"""

